/**
 * Embedded world data for the Location components: a land mask at 0.5° and simplified coastlines.
 *
 * Derived from Natural Earth (public domain) through world-atlas 2: the mask from land-50m, the coastlines from
 * land-110m, simplified to about 0.12° and stored at 0.1° precision. The strings are machine-generated: the mask is
 * run-length encoded (see landMask) and every line is a delta-encoded ring (see decodeRing), both in a URL-safe
 * base-64 varint alphabet. Everything is decoded lazily on first use, so importing the module costs nothing until a
 * component draws. Pure; safe on the server.
 */

/** Cell size of the land mask, in degrees. */
export const LAND_MASK_RESOLUTION = 0.5;
/** Columns of the land mask, from 180°W eastward. */
export const LAND_MASK_COLUMNS = 720;
/** Rows of the land mask, from 90°N southward. */
export const LAND_MASK_ROWS = 360;

/**
 * A line of coordinates: flat `[lon, lat, lon, lat, …]` pairs in degrees. Country rings are closed (the last
 * point repeats the first); coastlines are open polylines.
 */
export type GeoRing = Float32Array;

const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
let digits: Int8Array | null = null;

/**
 * Decodes the base-64 varint stream the data is stored in: each character carries 5 value bits, least significant
 * group first, and its sixth bit (32) says that another character follows.
 */
function decodeVarints(code: string): number[] {
  if (!digits) {
    digits = new Int8Array(128).fill(-1);
    for (let i = 0; i < ALPHABET.length; i++) digits[ALPHABET.charCodeAt(i)] = i;
  }
  const values: number[] = [];
  let value = 0;
  let shift = 0;
  for (let i = 0; i < code.length; i++) {
    const digit = digits[code.charCodeAt(i)];
    value += (digit & 31) * 2 ** shift;
    if (digit & 32) shift += 5;
    else {
      values.push(value);
      value = 0;
      shift = 0;
    }
  }
  return values;
}

/** Decodes one stored ring (zig-zag deltas in 0.1° steps) into flat lon/lat pairs. */
export function decodeRing(code: string): GeoRing {
  const values = decodeVarints(code);
  const ring = new Float32Array(values.length);
  let x = 0;
  let y = 0;
  for (let i = 0; i + 1 < values.length; i += 2) {
    const dx = values[i];
    const dy = values[i + 1];
    x += dx & 1 ? -(dx + 1) / 2 : dx / 2;
    y += dy & 1 ? -(dy + 1) / 2 : dy / 2;
    ring[i] = x / 10;
    ring[i + 1] = y / 10;
  }
  return ring;
}

let mask: Uint8Array | null = null;

/** The land mask, row-major from 90°N and 180°W, one byte per 0.5° cell: 1 is land, 0 is water. */
export function landMask(): Uint8Array {
  if (mask) return mask;
  const cells = new Uint8Array(LAND_MASK_COLUMNS * LAND_MASK_ROWS);
  // run lengths per row, alternating water and land, starting with water
  let index = 0;
  let land = 0;
  let column = 0;
  for (const run of decodeVarints(MASK)) {
    if (land) cells.fill(1, index, index + run);
    index += run;
    column += run;
    land ^= 1;
    if (column >= LAND_MASK_COLUMNS) {
      column = 0;
      land = 0;
    }
  }
  mask = cells;
  return cells;
}

/** Wraps a longitude into [-180, 180). */
const wrapLon = (lon: number) => ((((lon + 180) % 360) + 360) % 360) - 180;

/** True when the 0.5° cell that contains the point is land. Longitudes wrap; latitudes clamp. */
export function isLand(lat: number, lon: number): boolean {
  const row = Math.min(LAND_MASK_ROWS - 1, Math.max(0, Math.floor((90 - lat) / LAND_MASK_RESOLUTION)));
  const column = Math.min(LAND_MASK_COLUMNS - 1, Math.floor((wrapLon(lon) + 180) / LAND_MASK_RESOLUTION));
  return landMask()[row * LAND_MASK_COLUMNS + column] === 1;
}

/**
 * Share of land in a square of `size` degrees centred on the point, from 0 to 1. Use it for coarse dot maps,
 * where a dot that covers 2° should appear when most of its area is land, not when its centre happens to be.
 */
export function landCoverage(lat: number, lon: number, size: number): number {
  const steps = Math.max(1, Math.round(size / LAND_MASK_RESOLUTION));
  const start = -size / 2 + LAND_MASK_RESOLUTION / 2;
  let hits = 0;
  for (let i = 0; i < steps; i++) {
    for (let j = 0; j < steps; j++) {
      if (isLand(lat + start + i * LAND_MASK_RESOLUTION, lon + start + j * LAND_MASK_RESOLUTION)) hits++;
    }
  }
  return hits / (steps * steps);
}

let coast: GeoRing[] | null = null;

/**
 * The coastlines of every land mass (Natural Earth 110m, simplified) as 128 open polylines. Rings that
 * cross the antimeridian are cut there, so no segment jumps across a flat map; stroke each line as it is.
 */
export function coastlines(): readonly GeoRing[] {
  coast ??= COASTLINES.map(decodeRing);
  return coast;
}

